#ifndef ROUTE_MODELS_HPP
#define ROUTE_MODELS_HPP

#include <string>
#include <vector>
#include <utility>

/**
 * @brief Represents a single leg between two stops in a multi-destination delivery route.
 */
struct RouteLeg {
    int legIndex;                          // 1-based leg sequence number
    std::string from;                      // Origin location of this leg
    std::string to;                        // Destination location of this leg
    double distance;                       // Shortest path distance in kilometers
    std::vector<std::string> path;         // Ordered list of vertices along the shortest road path
};

/**
 * @brief Represents a single greedy decision step.
 * Recorded for viva explanation and frontend visualization playback.
 */
struct RouteSelectionStep {
    int stepNumber;
    std::string currentLocation;
    std::vector<std::string> unvisitedStops;
    std::vector<std::pair<std::string, double>> candidateDistances; // Distance to all candidate stops
    std::string selectedStop;
    double selectedDistance;
    std::string explanation;
};

/**
 * @brief Full delivery route result generated by an ordering strategy (Greedy or Baseline).
 */
struct RouteResult {
    std::string strategy;                  // "greedy" or "baseline"
    std::string startLocation;             // Warehouse / depot starting location
    std::vector<std::string> requestedStops;// Original requested stops
    std::vector<std::string> orderedStops;  // Chosen visiting order of delivery stops
    std::vector<std::string> fullPath;     // Complete stitched node-by-node path
    std::vector<RouteLeg> legs;            // Breakdown of individual legs
    double totalDistance = 0.0;            // Total route travel distance in km
    std::vector<std::string> unreachableStops; // Requested stops that could not be reached
    std::vector<RouteSelectionStep> executionTrace; // Step-by-step decision trace
    bool isComplete = true;                // True if all requested stops were visited
};

/**
 * @brief Comparison result between Greedy route and Baseline (input-order) route.
 */
struct RouteComparisonResult {
    RouteResult greedyRoute;
    RouteResult baselineRoute;
    double distanceDifference = 0.0;       // baselineDistance - greedyDistance (positive means greedy saved km)
    double percentageSavings = 0.0;        // (distanceDifference / baselineDistance) * 100
    bool greedyIsBetter = false;           // True if greedy strictly traveled less distance
    std::string analysisSummary;           // Textual explanation and heuristic limitations
};

#endif // ROUTE_MODELS_HPP
